from dataclasses import dataclass, field, fields
from typing import Annotated

import annotated_doc
import pytest
from typing_extensions import Doc

from fancy_dataclass.doc import DocDataclass, DocDataclassFieldSettings
from fancy_dataclass.utils import FieldTypeValidationError


def test_get_class_doc() -> None:
    """Tests the get_class_doc method."""
    # no doc kwarg, no class docstring
    @dataclass
    class DC1(DocDataclass):
        ...
    DC1.__doc__ = None
    assert DC1.get_class_doc() is None
    # yes doc kwarg, no class docstring
    @dataclass
    class DC2(DocDataclass, doc='doc'):
        ...
    DC2.__doc__ = None
    assert DC2.get_class_doc() == 'doc'
    # no doc kwarg, yes class docstring
    @dataclass
    class DC3(DocDataclass):
        """doc"""
    assert DC3.get_class_doc() == 'doc'
    # yes doc kwarg, yes class docstring
    @dataclass
    class DC4(DocDataclass, doc='doc1'):
        """doc2"""
    assert DC4.get_class_doc() == 'doc1'
    # __doc__ is auto-generated by `dataclass` decorator
    @dataclass
    class DC5(DocDataclass):
        ...
    assert DC5.get_class_doc() == 'DC5()'
    # __doc__ is not inherited by subclass
    class DC6(DC5):
        ...
    assert DC6.get_class_doc() is None
    # __doc__ is auto-generated by `dataclass` decorator
    DC6WithDoc = dataclass(DC6)
    assert DC6WithDoc.get_class_doc() == 'DC6()'

def test_get_field_doc() -> None:
    """Tests the get_field_doc method."""
    @dataclass
    class DC1(DocDataclass):
        a: int = 1  # no doc
        b: int = field(default=2, metadata={'doc': 'b'})  # metadata doc field
        c: Annotated[int, Doc('c')] = 3  # Annotated Doc field
        d: Annotated[int, 'd'] = 4  # string not wrapped in a Doc
        e: Annotated[int, Doc('bad'), Doc('e')] = 5  # multiple Docs (per PEP 727, use the last one)
        f: Annotated[int, Doc(None)] = 6  # None-valued Doc (currently permitted)
        g: Annotated[int, Doc('g1')] = field(
            default=7,
            metadata={'doc': 'g2'},
        )  # both Doc and metadata (latter takes precedence)
        # stringized annotations:
        # avoid evaluating them since that would occur at import time
        h: "Annotated[int, Doc('h')]" = 8
        # stringized annotation, fully qualified
        i: "typing_extensions.Annotated[int, typing_extensions.Doc('i')]" = 9  # type: ignore[name-defined]  # noqa: F821
        # this is OK since the Annotated part is not stringized
        j: Annotated['int', Doc('j')] = 10
        k: Annotated[int, annotated_doc.Doc('k')] = 11
        l: Annotated[int, Doc('bad'), annotated_doc.Doc('l')] = 12  # noqa: E741
    field_docs = {}
    for fld in fields(DC1):
        doc = DC1.get_field_doc(fld.name)
        settings = DC1._field_settings(fld.name, base=DocDataclass)
        assert settings == DocDataclassFieldSettings(doc=doc)
        field_docs[fld.name] = doc
    assert field_docs == {
        'a': None,
        'b': 'b',
        'c': 'c',
        'd': None,
        'e': 'e',
        'f': None,
        'g': 'g2',
        'h': None,
        'i': None,
        'j': 'j',
        'k': 'k',
        'l': 'l',
    }
    @dataclass
    class DC2(DocDataclass):
        x: 'fake-type'  # type: ignore  # noqa: F821
    assert DC2.get_field_doc('x') is None
    # Doc with non-string field is not allowed
    with pytest.raises(FieldTypeValidationError, match="field 'doc' .*: value 1 does not match"):
        @dataclass
        class DC3(DocDataclass):
            x: Annotated[int, Doc(1)] = 1
    with pytest.raises(FieldTypeValidationError, match="field 'doc' .*: value 1 does not match"):
        @dataclass
        class DC4(DocDataclass):
            x: int = field(metadata={'doc': 1})
